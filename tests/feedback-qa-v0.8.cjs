'use strict';
// V0.8 isolated Chromium QA. Synthetic fixture only; NEVER write to the real Google Sheet.
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const path=require('node:path');
const fs=require('node:fs');
const {pathToFileURL}=require('node:url');
const html=path.join(__dirname,'../docs/apercu-sportos-v0.8.html');
(async()=>{
 assert(fs.existsSync(html));
 const browser=await chromium.launch({headless:true});
 const output=path.join(__dirname,'../artifacts/v0.8');
 fs.mkdirSync(output,{recursive:true});
 const page=await browser.newPage({viewport:{width:1280,height:830}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const open=async tab=>{await page.locator('[data-nav="program"]').first().click();await page.locator('[data-program-tab="'+tab+'"]').click()};
 try{
  await page.goto(pathToFileURL(html).href,{waitUntil:'load'});
  await page.locator('.sp7-page').waitFor();
  assert.match(await page.locator('.so8-adaptation').innerText(),/Pas de séance terminée la semaine précédente/);
  await open('B');
  await page.locator('.sp7-primary').click();
  await page.locator('.so-session-page').waitFor();
  assert.equal(await page.locator('#f-secondsReserve4').count(),1,'Timed gainage has second-based reserve');
  assert.equal(await page.locator('#f-rir4').count(),0,'Timed gainage must not ask repetition reserve');
  assert.equal(await page.locator('#f-rir0').count(),1,'Repetition-based exercise keeps RIR');
  await page.locator('.so-exercise').last().locator('summary').click();
  await page.locator('#f-sets4').fill('2');
  await page.locator('#f-seconds4').fill('40');
  await page.locator('#f-secondsReserve4').fill('12');
  await page.locator('#f-difficulty4').selectOption('Modéré');
  await page.locator('#f-pain4').selectOption('Non');
  await page.locator('#modal-submit').click();
  await page.locator('.so-session-page').waitFor({state:'detached'});
  let state=await page.evaluate(()=>({logs:window.__SPORTOS_FIXTURE__.logs.filter(x=>x.Exercice_ID==='EX-GAINAGE')}));
  assert(state.logs.some(x=>String(x['Réserve tenue (s)'])==='12'),'Gainage reserve recorded in synthetic data');
  console.log('V08_GAINAGE_SECONDS=PASS');
  await open('Vélo');
  await page.locator('.sp7-primary').click();
  await page.locator('#f-duration').fill('45');
  await page.locator('#f-distance').fill('12.5');
  await page.locator('#f-elevationGain').fill('245');
  await page.locator('#f-averageSpeed').fill('18.6');
  await page.locator('#f-effort').fill('3');
  await page.locator('#f-pain').selectOption('Non');
  await page.locator('#modal-submit').click();
  await page.locator('.so-session-page').waitFor({state:'detached'});
  state=await page.evaluate(()=>({bike:window.__SPORTOS_FIXTURE__.cardio.find(x=>x.Type==='Vélo')}));
  assert.equal(String(state.bike['Dénivelé positif (m)']),'245');
  assert.equal(String(state.bike['Vitesse moyenne (km/h)']),'18.6');
  console.log('V08_STRAVA_MANUAL_BIKE=PASS');
  await open('A');
  await page.locator('.sp7-primary').click();
  await page.locator('#f-sets0').fill('2');
  await page.locator('#f-reps0').fill('15');
  await page.locator('#f-rir0').selectOption('3');
  await page.locator('#f-difficulty0').selectOption('Modéré');
  await page.locator('#f-pain0').selectOption('Non');
  await page.locator('#modal-submit').click();
  await page.locator('.so-session-page').waitFor({state:'detached'});
  assert.equal(await page.locator('.so8-celebration').count(),1,'Four distinct completed sports show persistent celebration');
  assert.match(await page.locator('.so8-celebration').innerText(),/Félicitations/);
  const completion=await page.locator('.sp7-head-stat').innerText();
  assert.match(completion,/4\s*\/04/);
  console.log('V08_WEEK_COMPLETE_FOUR_TYPES=PASS');
  await page.evaluate(()=>{const d=window.__SPORTOS_FIXTURE__;d.today='2026-10-26';const run=d.cardio.find(x=>x.Type==='Course');run.Douleur='Non';run.Course_sec_bloc='60';run.Marche_sec_bloc='60';run.Nb_blocs='8'});
  await open('A');
  assert.equal(await page.locator('.so8-celebration').count(),0,'Past week celebration does not persist into next week');
  assert.match(await page.locator('.so8-adaptation').innerText(),/ajustements mesurés/i,'Prior logged easy A session triggers cautious improvement');
  assert.match(await page.locator('.sp7-ex').first().innerText(),/16 répétitions/,'One extra rep target');
  await open('B');
  assert.match(await page.locator('.sp7-ex').last().innerText(),/45 secondes/,'Gainage increases by only 5 sec');
  await open('Course');
  assert.match(await page.locator('.so8-adaptation').innerText(),/70 s course/,'Course interval increase 10 sec');
  await open('Vélo');
  assert.match(await page.locator('.so8-adaptation').innerText(),/50 min/,'Bike plan increased only 5 min');
  console.log('V08_WEEKLY_PLAN_ADAPTATION=PASS');
  await page.evaluate(()=>{
    const d=window.__SPORTOS_FIXTURE__;
    const a=d.sessions.find(x=>x.Type==='A'&&x.Statut==='Terminée');
    d.logs.find(x=>x.Seance_ID===a.Seance_ID&&x.Exercice_ID==='EX-SQUAT').Douleur='Oui';
  });
  await open('A');
  assert.match(await page.locator('.so8-adaptation').innerText(),/Douleur signalée/);
  assert.doesNotMatch(await page.locator('.sp7-ex').first().innerText(),/13 répétitions/);
  console.log('V08_PAIN_VETO=PASS');
  for(const width of [320,390,768,1280]){
    await page.setViewportSize({width,height:800});
    await page.screenshot({path:path.join(output,'sportos-v08-'+width+'.png'),fullPage:true});
    const w=await page.evaluate(()=>[document.documentElement.scrollWidth,innerWidth]);
    assert(w[0]<=w[1]+2,'Horizontal overflow '+width);
  }
  console.log('V08_RESPONSIVE=PASS');
  assert.equal(errors.length,0,errors.join(' ; '));
  console.log('SPORTOS_V08_CHROMIUM=PASS; SHEET_WRITES=0');
 }finally{await browser.close()}
})().catch(err=>{console.error(err);process.exitCode=1});
